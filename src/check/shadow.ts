// Shadow files: one checked JavaScript file per page, in which every expression of
// the page appears verbatim, inside nested blocks that declare what it can see.
// TypeScript checks the file (`checkJs`); `mapLine` turns its positions back into
// positions in the HTML.
import { dirname, relative } from 'node:path';
import type { CheckLoc, CheckUnit, TypeRef } from '../compiler/check-unit.js';
import type { HelperManifest } from '../compiler/compile.js';
import { STORE_FNS, BUILTIN_HELPERS } from '../compiler/expr.js';
import { MESSAGES } from '../compiler/index.js';
import { schemaToTs, typeName } from './openapi-types.js';

export interface ShadowOptions {
  unit: CheckUnit;
  /** absolute path the shadow file is written to */
  file: string;
  /** project root; root-relative module specifiers (`/src/x.js`) resolve against it */
  root: string;
  /** absolute path of the declarations sinter writes next to the shadow files (`sinter.d.ts`) */
  declarations: string;
  /** the types module and the names it exports */
  types: { file: string; names: string[] } | null;
  helpers: HelperManifest;
  /** the actions module, for `data-sn-call` arguments and results */
  actions?: HelperManifest;
  /** absolute paths of the declarations generated per OpenAPI spec, by spec index */
  openapi?: string[];
}

/** A run of shadow lines that came from the HTML. */
export interface Region {
  /** first shadow line, 1-based */
  start: number;
  lines: number;
  loc: CheckLoc;
  /** every line maps to `loc` itself (a `type` attribute in a JSDoc comment) */
  fixed?: boolean;
}

export interface Shadow {
  text: string;
  regions: Region[];
  /** first line of the broken expressions (written last); nothing from there on is reported */
  brokenFrom: number | null;
}

export function shadow(o: ShadowOptions): Shadow {
  const { unit } = o;
  const out: string[] = [];
  const regions: Region[] = [];
  const line = (s: string) => out.push(s);
  /** writes `src` from column 1 of the next line, so columns after its first line are the HTML's own */
  const verbatim = (src: string, loc: CheckLoc) => {
    const lines = src.split('\n');
    regions.push({ start: out.length + 1, lines: lines.length, loc });
    out.push(...lines);
  };
  const spec = (target: string) => {
    let s = relative(dirname(o.file), target).split('\\').join('/');
    if (!s.startsWith('.')) s = './' + s;
    return s;
  };
  const moduleSpec = (m: string) => (m.startsWith('/') ? spec(o.root + m) : m);
  const sinter = spec(o.declarations).replace(/\.d\.ts$/, '');
  const decl = (name: string) => `import('${sinter}').${name}`;

  line('// @ts-check');
  line(`// Generated by \`sinter check\` from ${relative(o.root, unit.file).split('\\').join('/')}. Do not edit.`);
  if (o.types?.names.length) line(`/** @import { ${o.types.names.join(', ')} } from '${spec(o.types.file).replace(/\.(d\.)?ts$/, '')}' */`);
  const refs = unit.exprs.flatMap((e) => [e.resultType, e.returns, e.payload?.type]);
  const specs = new Set([
    ...unit.resources.flatMap((r) => (r.openapi && !r.type ? [r.openapi.spec] : [])),
    ...refs.flatMap((t) => (t?.kind === 'openapi' ? [t.spec] : [])),
  ]);
  for (const i of [...specs].sort()) line(`/** @import * as $O${i} from '${spec(o.openapi![i]!).replace(/\.d\.ts$/, '')}' */`);

  // names a page can see besides its own frames; resources first, as sinter resolves them
  const taken = new Set<string>(unit.resources.map((r) => r.name));
  for (const n of ['$any', '$item', '$el', '$event', '$result', '$error', '$meta', '$url', '$now', '$locale', ...STORE_FNS]) taken.add(n);
  const builtin = BUILTIN_HELPERS.filter((h) => !taken.has(h));
  for (const h of builtin) taken.add(h);
  line(`import { ${builtin.join(', ')} } from '${sinter}';`);
  const userHelpers = o.helpers.names.filter((h) => !taken.has(h));
  if (o.helpers.module && userHelpers.length) line(`import { ${userHelpers.join(', ')} } from '${moduleSpec(o.helpers.module)}';`);
  for (const [ns, { module }] of Object.entries(o.helpers.namespaces)) {
    // the built-in messages: `m`, typed by the generated `src/sinter.messages.d.ts`
    if (!taken.has(ns)) line(module === MESSAGES ? `import { m as ${ns} } from '${MESSAGES}';` : `import * as ${ns} from '${moduleSpec(module)}';`);
  }
  if (o.actions?.module && (unit.resources.some((r) => r.call) || unit.exprs.some((e) => e.returns?.kind === 'call' || e.resultType?.kind === 'call'))) {
    line(`import * as $A from '${moduleSpec(o.actions.module)}';`);
  }
  line('const $any = /** @type {any} */ (null);');
  /** what a resource fed by `call` holds: the awaited result, at its `items` path */
  const callResult = (c: { name: string; items: string | null }) =>
    `Awaited<ReturnType<typeof $A.${c.name}>>${(c.items ? c.items.split('.') : []).map((k) => `[${JSON.stringify(k)}]`).join('')}`;

  const types: string[] = [];
  for (const r of unit.resources) {
    const t = r.type ?? 'any';
    types.push(`${JSON.stringify(r.name)}: ${t}`);
    if (r.type) {
      line('/**');
      line(' * @type {');
      verbatim(r.type, r.loc);
      regions[regions.length - 1]!.fixed = true;
      line(' * }');
      line(' */');
    } else if (r.call) {
      const t = callResult(r.call);
      types[types.length - 1] = `${JSON.stringify(r.name)}: ${t}`;
      line(`/** @type {${t}} */`);
    } else if (r.openapi) {
      const t = schemaToTs(r.openapi.schema, (n) => `$O${r.openapi!.spec}.${typeName(n)}`);
      types[types.length - 1] = `${JSON.stringify(r.name)}: ${t}`;
      regions.push({ start: out.length + 1, lines: 1, loc: r.loc, fixed: true });
      line(`/** @type {${t}} ${r.openapi.label.replace(/\*\//g, '')} */`);
    } else line('/** @type {any} */');
    regions.push({ start: out.length + 1, lines: 1, loc: r.nameLoc ?? r.loc, fixed: true });
    line(`const ${r.name} = $any;`);
    // with `type`, what the action returns (at `items`) must fit it; reported on `type`
    if (r.call && r.type) {
      // own line: TypeScript drops a JSDoc tag that follows `{` on the same line
      line('{');
      regions.push({ start: out.length + 1, lines: 1, loc: r.loc, fixed: true });
      line(`/** @type {${r.type.replace(/\s+/g, ' ')}} */ const $fits = /** @type {${callResult(r.call)}} */ ($any); void $fits;`);
      line('}');
    }
  }
  const names = unit.resources.map((r) => JSON.stringify(r.name)).join(' | ') || 'never';
  line(`/** @type {Record<${names}, ${decl('Meta')}>} */`);
  line('const $meta = $any;');
  line('/** @type {Record<string, any>} */');
  line('const $url = $any;');
  line('/** @type {Date} */');
  line('const $now = $any;');
  line('/** @type {string} */');
  line('let $locale = $any;');
  const directions = unit.resources.filter((r) => r.directions).map((r) => JSON.stringify(r.name)).join(' | ') || 'never';
  line(`/** @type {${decl('Store')}<{ ${types.join('; ')} }, ${directions}>} */`);
  line(`const { ${STORE_FNS.filter((f) => !unit.resources.some((r) => r.name === f)).join(', ')} } = $any;`);
  line(`/** @template T @param {T} list @returns {${decl('Item')}<T>} */`);
  line('function $item(list) { return $any; }');

  /** a JSDoc tag with a type; a type the app wrote maps its errors to where it was written */
  const tagged = (tag: string, t: TypeRef, after = '') => {
    if (t.kind === 'ts') {
      line(`/** @${tag} {`);
      verbatim(t.text, t.loc);
      regions[regions.length - 1]!.fixed = true;
      line(`} */${after}`);
      return;
    }
    const text = t.kind === 'decl' ? decl(t.name) : t.kind === 'names' ? t.names.map((n) => JSON.stringify(n)).join(' | ') : t.kind === 'openapi'
      ? schemaToTs(t.schema, (n) => `$O${t.spec}.${typeName(n)}`)
      : t.kind === 'call'
        ? (t.args ? `${decl('CallArgs')}<typeof $A.${t.name}>` : `Awaited<ReturnType<typeof $A.${t.name}>>`)
        : t.kind === 'resource' ? `typeof ${t.resource}`
        : `${t.partial ? 'Partial<' : ''}${decl('Item')}<typeof ${t.resource}>${t.partial ? '>' : ''}`;
    line(`/** @${tag} {${text}} */${after}`);
  };

  /** declarations for the frames of an expression; returns the number of blocks opened */
  const open = (frames: number[]): number => {
    for (const i of frames) {
      const f = unit.frames[i]!;
      line('{');
      // declarations map to where the HTML writes the names, for go to definition
      const at = (loc: CheckLoc | undefined) => { if (loc) regions.push({ start: out.length + 1, lines: 1, loc, fixed: true }); };
      if (f.kind === 'state') {
        line('let {');
        f.names.forEach((n, k) => { at(f.locs?.[k]); line(`${n},`); });
        line(`} = ${f.init === null ? '$any' : `$e${f.init}()`};`);
      } else if (f.kind === 'formError') {
        line(`/** @type {${decl('Err')} | null} */ let $error = $any;`);
      } else if (f.kind === 'let') {
        at(f.loc);
        line(`const ${f.name} = ${f.init === null ? '$any' : `$e${f.init}()`};`);
      } else {
        at(f.loc);
        line(`const ${f.item} = ${f.init === null ? '$any' : `$item($e${f.init}())`};`);
        if (f.index) { at(f.indexLoc); line(`const ${f.index} = 0;`); }
      }
    }
    return frames.length;
  };

  // broken expressions last, so their syntax errors cannot spill into checked code
  const order = unit.exprs.map((e, i) => [e, i] as const).sort(([a], [b]) => Number(!!a.broken) - Number(!!b.broken));
  let brokenFrom: number | null = null;
  order.forEach(([e, i]) => {
    if (e.broken && brokenFrom === null) brokenFrom = out.length + 1;
    line('');
    if (e.returns) tagged('returns', e.returns);
    line(`function $e${i}() {`);
    // the payload's block is outside the frames: state and lets shadow its fields, as sinter resolves them
    if (e.payload) {
      line('{');
      if (e.payload.type) tagged('type', e.payload.type, ' const $p = $any;');
      else line('const $p = $any;');
      // a field the payload type lacks is reported at the start of the expression
      for (const n of e.payload.names) {
        regions.push({ start: out.length + 1, lines: 1, loc: e.loc, fixed: true });
        line(`const ${n} = $p.${n};`);
      }
      // a state or let name shadows a payload field of the same name: an error when the payload type has it
      if (e.payload.type) {
        const shadowing = [...(e.payload.states ?? []).map((n) => [n, 'state', 'the state'] as const), ...(e.payload.lets ?? []).map((n) => [n, '`data-sn-let` name', 'it'] as const)];
        for (const [n, what, it] of shadowing) {
          const msg = `${what} \`${n}\` shadows the payload field \`${n}\`: rename ${it}`;
          regions.push({ start: out.length + 1, lines: 1, loc: e.loc, fixed: true });
          line(`/** @type {${JSON.stringify(n)} extends keyof typeof $p ? ${JSON.stringify(msg)} : true} */ const $shadows_${n} = true; void $shadows_${n};`);
        }
      }
    }
    const blocks = open(e.frames) + (e.payload ? 1 : 0);
    line(`/** @type {${decl(`El<${JSON.stringify(e.tag)}>`)}} */ const $el = $any;`);
    if (e.mode === 'value') {
      // action arguments and bodies are taken when the trigger fires
      // run('id') starts the action without an event: unguarded reads are reported
      if (e.event !== null) line(`/** @type {${decl(e.run ? `RunEvent<${decl(`Ev<${JSON.stringify(e.event)}>`)}>` : `Ev<${JSON.stringify(e.event)}>`)}} */ const $event = $any;`);
      // a value of the wrong type as a whole is reported on `return`
      regions.push({ start: out.length + 1, lines: 1, loc: e.loc, fixed: true });
      line('return (');
      verbatim(e.src, e.loc);
      line(');');
    } else {
      line(`/** @type {${decl(`Ev<${JSON.stringify(e.event ?? '')}>`)}} */ const $event = $any;`);
      if (e.result) {
        if (e.resultType) tagged('type', e.resultType, ' const $result = $any;');
        else line('/** @type {any} */ const $result = $any;');
      }
      if (e.error) line(`/** @type {${decl('Err')}} */ const $error = $any;`);
      verbatim(e.src, e.loc);
      line(';');
    }
    for (let b = 0; b < blocks; b++) line('}');
    line('}');
  });
  return { text: out.join('\n') + '\n', regions, brokenFrom };
}

/** Maps a 1-based shadow position to the HTML, or null for generated lines. */
export function mapPosition(regions: Region[], line: number, col: number): CheckLoc | null {
  for (const r of regions) {
    if (line < r.start || line >= r.start + r.lines) continue;
    if (r.fixed) return r.loc;
    const k = line - r.start;
    return { ...r.loc, line: r.loc.line + k, col: k === 0 ? r.loc.col + col - 1 : col };
  }
  return null;
}

