// JSON Schema (OpenAPI 3.0 and 3.1) to TypeScript, for `sinter check`. Named
// schemas (`components.schemas`) become named declarations, so messages say
// `type 'Article'`. Precision where checking expressions needs it (properties,
// arrays, unions, enums); `any` where it does not (formats, patterns, limits).

type Json = Record<string, unknown>;
const isObj = (v: unknown): v is Json => typeof v === 'object' && v !== null && !Array.isArray(v);
const SCHEMA_REF = '#/components/schemas/';

/** A schema name as a TypeScript identifier. */
export function typeName(name: string): string {
  const id = name.replace(/[^\w$]/g, '_');
  return /^\d/.test(id) ? '_' + id : id;
}

const key = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));

/** TypeScript for a schema; `ref` turns a named schema into a type reference. */
export function schemaToTs(schema: unknown, ref: (name: string) => string, depth = 0): string {
  if (schema === true || schema === undefined) return 'any';
  if (schema === false) return 'never';
  if (!isObj(schema) || depth > 24) return 'any';
  const s = schema;
  if (typeof s.$ref === 'string') {
    return s.$ref.startsWith(SCHEMA_REF) ? ref(s.$ref.slice(SCHEMA_REF.length).replace(/~1/g, '/').replace(/~0/g, '~')) : 'any';
  }
  const sub = (v: unknown) => schemaToTs(v, ref, depth + 1);
  let t: string;
  if ('const' in s) t = JSON.stringify(s.const);
  else if (Array.isArray(s.enum)) t = s.enum.map((v) => JSON.stringify(v)).join(' | ') || 'never';
  else if (Array.isArray(s.allOf)) t = s.allOf.map((x) => paren(sub(x))).join(' & ');
  else if (Array.isArray(s.oneOf) || Array.isArray(s.anyOf)) t = ((s.oneOf ?? s.anyOf) as unknown[]).map(sub).join(' | ');
  else {
    const types = Array.isArray(s.type) ? s.type.map(String) : typeof s.type === 'string' ? [s.type] : [];
    if (!types.length && (isObj(s.properties) || 'additionalProperties' in s)) types.push('object');
    if (!types.length && 'items' in s) types.push('array');
    t = types.length ? types.map((ty) => single(ty, s, sub)).join(' | ') : 'any';
  }
  if (s.nullable === true && t !== 'any') t = `${paren(t)} | null`;
  return t;
}

function single(type: string, s: Json, sub: (v: unknown) => string): string {
  switch (type) {
    case 'string': return 'string';
    case 'number': case 'integer': return 'number';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': return `${paren(sub(s.items))}[]`;
    case 'object': {
      const props = isObj(s.properties) ? s.properties : {};
      const required = new Set(Array.isArray(s.required) ? s.required.map(String) : []);
      const parts = Object.entries(props).map(([k, v]) => `${key(k)}${required.has(k) ? '' : '?'}: ${sub(v)}`);
      const extra = s.additionalProperties;
      if (extra === true || isObj(extra)) parts.push(`[key: string]: ${extra === true ? 'any' : sub(extra)}`);
      else if (!parts.length && extra === undefined) parts.push('[key: string]: any');
      return `{ ${parts.join('; ')} }`;
    }
    default: return 'any';
  }
}

const paren = (t: string) => (/[|&]/.test(t) && !/^\{.*\}$/.test(t) ? `(${t})` : t);

/** Declarations for every named schema of a spec: interfaces for objects, aliases otherwise. */
export function specDeclarations(doc: unknown, file: string): string {
  const out = [`// Generated by \`sinter check\` from ${file}. Do not edit.`, 'export {};'];
  const schemas = isObj(doc) && isObj(doc.components) && isObj(doc.components.schemas) ? doc.components.schemas : {};
  const ref = (n: string) => typeName(n);
  for (const [name, schema] of Object.entries(schemas)) {
    const t = schemaToTs(schema, ref);
    // a plain object type becomes an interface, which keeps its name in messages
    if (/^\{ .* \}$/s.test(t) && !/\} [|&] \{/.test(t)) out.push(`export interface ${typeName(name)} ${t}`);
    else out.push(`export type ${typeName(name)} = ${t};`);
  }
  return out.join('\n') + '\n';
}
