import { MESSAGES as MESSAGES_MODULE } from './compiler/index.js';
const IDENT = /^[A-Za-z_$][\w$]*$/;

export interface MessagesProject {
  /** the inlang project directory (`project.inlang`) */
  dir: string;
  base: string;
  locales: string[];
  /** message files by locale */
  files: Record<string, string>;
  dicts: Record<string, Record<string, string>>;
  /** every key of the base language, with the `{param}`s of its text */
  keys: Record<string, string[]>;
  diagnostics: Diagnostic[];
}

/**
 * Reads an inlang project (`project.inlang/settings.json`: `baseLocale`, `locales`, and the
 * message-format plugin's `pathPattern`, relative to the directory holding the project). Null when
 * there is none. Messages are plain strings with `{param}` placeholders; anything else is reported.
 */
export function readMessages(root: string, project = 'project.inlang'): MessagesProject | null {
  const dir = resolve(root, project), settingsFile = resolve(dir, 'settings.json');
  if (!existsSync(settingsFile)) return null;
  const diagnostics: Diagnostic[] = [];
  const fail = (file: string, message: string) => diagnostics.push({ severity: 'error', code: 'SN307', message, file, line: 1, col: 1 });
  let settings: { baseLocale?: unknown; locales?: unknown; 'plugin.inlang.messageFormat'?: { pathPattern?: unknown } };
  try { settings = JSON.parse(readFileSync(settingsFile, 'utf8')); } catch (e) { fail(settingsFile, `inlang settings cannot be read: ${(e as Error).message}`); return { dir, base: 'en', locales: [], files: {}, dicts: {}, keys: {}, diagnostics }; }
  const base = typeof settings.baseLocale === 'string' ? settings.baseLocale : 'en';
  const locales = Array.isArray(settings.locales) ? settings.locales.filter((l): l is string => typeof l === 'string') : [base];
  if (!locales.includes(base)) locales.unshift(base);
  const pattern = settings['plugin.inlang.messageFormat']?.pathPattern;
  const pathPattern = typeof pattern === 'string' ? pattern : './messages/{locale}.json';
  const files: Record<string, string> = {}, dicts: Record<string, Record<string, string>> = {};
  for (const l of locales) {
    const file = resolve(dirname(dir), pathPattern.replace('{locale}', l));
    files[l] = file;
    let raw: Record<string, unknown> = {};
    try { raw = JSON.parse(readFileSync(file, 'utf8')); } catch (e) { fail(file, `message file for \`${l}\` cannot be read: ${(e as Error).message}`); }
    const dict: Record<string, string> = {};
    for (const [k, v] of Object.entries(raw)) {
      if (k === '$schema') continue;
      if (typeof v !== 'string') { fail(file, `message \`${k}\` (${l}) is not a plain string: sinter's messages have no plurals or variants yet`); continue; }
      if (!IDENT.test(k)) { fail(file, `message key \`${k}\` is not an identifier, so \`m.${k}()\` cannot name it`); continue; }
      dict[k] = v;
    }
    dicts[l] = dict;
  }
  const keys: Record<string, string[]> = {};
  for (const [k, v] of Object.entries(dicts[base] ?? {})) keys[k] = [...new Set([...v.matchAll(/\{(\w+)\}/g)].map((x) => x[1]!))];
  return { dir, base, locales, files, dicts, keys, diagnostics };
}

/** `src/sinter.messages.d.ts`: one method per key, typed from the base language's placeholders. */
export function messagesDts(p: MessagesProject): string {
  const lines = [
    `// Generated by sinter from ${p.files[p.base] ? 'the inlang project' : 'messages'}: \`m\` from '${MESSAGES_MODULE}', and \`m.key()\` in markup. Do not edit.`,
    `import '${MESSAGES_MODULE}';`,
    '',
    `declare module '${MESSAGES_MODULE}' {`,
    '  interface Messages {',
  ];
  for (const [k, params] of Object.entries(p.keys).sort(([a], [b]) => a.localeCompare(b))) {
    const text = (p.dicts[p.base]![k] ?? '').replace(/\*\//g, '* /').replace(/\n/g, ' ');
    lines.push(`    /** ${text} */`);
    lines.push(params.length ? `    ${k}(params: { ${params.map((x) => `${x}: string | number`).join('; ')} }): string;` : `    ${k}(): string;`);
  }
  lines.push('  }', '}', '');
  return lines.join('\n');
}

/**
 * The message keys a module uses through `m` imported from the messages module: `m.key` only.
 * Any other use of `m` (`m[k]`, passing `m` on) is an error, since the page's language file could
 * not be cut to what it uses.
 */
export function moduleKeys(code: string, id: string): { keys: string[]; errors: string[] } {
  if (!code.includes(MESSAGES_MODULE)) return { keys: [], errors: [] };
  let ast: ReturnType<typeof parseModule>;
  try { ast = parseModule(code, id.replace(/\?.*$/, '')); } catch { return { keys: [], errors: [] }; }
  const names = new Set<string>(), locals = new Set<unknown>();
  for (const st of ast.body) {
    if (st.type !== 'ImportDeclaration' || st.source.value !== MESSAGES_MODULE) continue;
    for (const s of st.specifiers) {
      if (s.type === 'ImportSpecifier' && (s.imported.type === 'Identifier' ? s.imported.name : s.imported.value) === 'm') { names.add(s.local.name); locals.add(s.local); }
    }
  }
  if (!names.size) return { keys: [], errors: [] };
  const keys = new Set<string>(), errors: string[] = [], ok = new Set<unknown>(locals);
  const where = (pos: number) => { const before = code.slice(0, pos).split('\n'); return `${id}:${before.length}:${before.at(-1)!.length + 1}`; };
  simple(ast as never, {
    MemberExpression(n: any) {
      if (n.object.type === 'Identifier' && names.has(n.object.name)) {
        ok.add(n.object);
        if (!n.computed && n.property.type === 'Identifier') keys.add(n.property.name);
        else errors.push(`${where(n.start)}: \`${n.object.name}[…]\`: messages are named literally (\`m.key()\`), so each page's language file holds only what it uses`);
      }
    },
  }, tsBase as never);
  simple(ast as never, {
    Identifier(n: any) {
      if (names.has(n.name) && !ok.has(n)) errors.push(`${where(n.start)}: \`${n.name}\` is used other than as \`${n.name}.key\`; call messages by name, e.g. \`${n.name}.nav_mail()\``);
    },
  }, tsBase as never);
  return { keys: [...keys].sort(), errors };
}

/** acorn-walk's walker, with TypeScript's nodes: expressions inside casts are walked, types skipped */
const tsBase = new Proxy(base as Record<string, unknown>, {
  get(t, k: string) {
    if (k in t) return t[k];
    if (/^TS(As|Satisfies|NonNull)Expression$|^TSTypeAssertion$|^TSInstantiationExpression$/.test(k)) return (n: any, st: unknown, c: (n: unknown, st: unknown) => void) => c(n.expression, st);
    return () => {};
  },
});

/** One page's file for one language: an ES module that stores the dictionary on the shared state. */
export function languageFile(locale: string, dict: Record<string, string>): string {
  const g = 'globalThis[Symbol.for("sinter.i18n")]';
  return `const g=${g}||(${g}={dicts:{}});(g.dicts||(g.dicts={}))[${JSON.stringify(locale)}]=${JSON.stringify(dict)};g.loaded&&g.loaded(${JSON.stringify(locale)});\n`;
}

/**
 * The picker: the start of the shared head script (vite.ts), first in the head. It runs while the
 * head is parsed, picks the locale (the stored choice, then navigator.languages, exactly or by
 * language, then the base), sets `<html lang>` and adds the page's language file as a module
 * script: nothing waits for it. Its data is in `data-sn-i18n` on its own tag (on a page without
 * messages there is none, and it does nothing). The HTML has the base language's text
 * (`data-sn-m`, see `baseMessages` in the compiler): for another language those elements keep
 * their space but stay invisible until the page module has rendered them (`use(app)` in the
 * messages module), so no visitor sees one language replaced by another. If the page module has not
 * mounted after 3 s (it failed or stalls), the elements show again, in the base language.
 */
export const I18N_PICKER = `/* sinter i18n */(function(){try{var e=document.currentScript,c=JSON.parse(e.getAttribute("data-sn-i18n")),K=Symbol.for("sinter.i18n"),g=globalThis[K]||(globalThis[K]={dicts:{}}),L=c.locales,s=null;try{s=localStorage.getItem(c.storage)}catch(x){}function f(l){if(!l)return;l=l.toLowerCase();for(var i=0;i<L.length;i++)if(L[i].toLowerCase()==l)return L[i];for(i=0;i<L.length;i++)if(L[i].toLowerCase()==l.split("-")[0])return L[i]}var n=navigator.languages&&navigator.languages.length?navigator.languages:[navigator.language],r=f(s);for(var i=0;!r&&i<n.length;i++)r=f(n[i]);g.locale=r||c.base;g.base=c.base;g.locales=L;g.storage=c.storage;g.files=c.files;g.dicts=g.dicts||{};document.documentElement.lang=g.locale;if(g.locale!=c.base)try{var h=new CSSStyleSheet;h.replaceSync("[data-sn-m]{visibility:hidden}");document.adoptedStyleSheets=document.adoptedStyleSheets.concat(h);g.hide=h;setTimeout(function(){if(g.hide===h){document.adoptedStyleSheets=document.adoptedStyleSheets.filter(function(y){return y!==h});delete g.hide}},3e3)}catch(x){}var t=document.createElement("script");t.type="module";t.src=c.files[g.locale];document.head.appendChild(t)}catch(x){}})();\n`;
